namespace CGD.Level
{
    // Where along a building's hall a space goes.
    public enum BuildingSpacePlacement
    {
        Anywhere,   // anywhere along either side of the hall
        Entrance,   // first in line, beside the front door (reception, a principal's office)
        Back,       // across the far end of the hall, the full width of the building (a gym, an operating theatre)
    }
}
